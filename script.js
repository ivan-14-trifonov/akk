let currentCourse = 1;
let currentView = "matrix";

const matrixBody = document.querySelector("#matrix-body");
const planGrid = document.querySelector("#plan-grid");
const lessonsList = document.querySelector("#lessons-list");
const courseButtons = document.querySelector("#course-buttons");
const currentCourseLabel = document.querySelector("#current-course-label");
const planTitle = document.querySelector("#plan-title");
const lessonsTitle = document.querySelector("#lessons-title");
const practiceLink = document.querySelector("#practice-link");
const referenceNotice = document.querySelector("#reference-notice");

function markRefs(text) {
  return text.replace(/\((\d+(?:\.\d+)?(?:-\d+(?:\.\d+)?)?)\)/g, '(<span class="ref">$1</span>)');
}

function getCourse(id = currentCourse) {
  return courses.find((course) => course.id === id);
}

function renderCourseButtons() {
  courseButtons.innerHTML = courses
    .map((course) => {
      const active = course.id === currentCourse ? " is-active" : "";
      return `<button class="course-button${active}" type="button" data-course="${course.id}" aria-label="Открыть курс ${course.id}">${course.id}</button>`;
    })
    .join("");
}

function renderMatrix() {
  matrixBody.innerHTML = courses
    .map((course) => {
      const cells = course.matrix.map((value) => `<td>${markRefs(value || "—")}</td>`).join("");
      return `
        <tr>
          <td class="course-cell">
            Курс ${course.id}
            <button class="matrix-jump" type="button" data-course="${course.id}" data-view="plan">Подробнее</button>
          </td>
          ${cells}
        </tr>
      `;
    })
    .join("");
}

function renderPlan() {
  const course = getCourse();
  planTitle.textContent = `${course.id}. ${course.title}`;
  planGrid.innerHTML = fields
    .map((field, index) => {
      const value = course.plan[index] || "—";
      return `
        <article class="detail-item">
          <h3>${field}</h3>
          <p>${markRefs(value)}</p>
        </article>
      `;
    })
    .join("");
}

function renderLessons() {
  const course = getCourse();
  lessonsTitle.textContent = `${course.id}. ${course.title}`;
  practiceLink.href = `course-${course.id}.pdf`;
  practiceLink.firstChild.textContent = `Открыть / скачать практикум для курса ${course.id}`;
  lessonsList.innerHTML = course.lessons
    .map((lesson, index) => {
      const open = index === 0 ? " open" : "";
      const body = lesson.body.map((paragraph) => `<p>${markRefs(paragraph)}</p>`).join("");
      return `
        <details class="lesson-card"${open}>
          <summary>${lesson.title}</summary>
          <div class="lesson-body">${body}</div>
        </details>
      `;
    })
    .join("");
}

function setView(view) {
  currentView = view;
  document.querySelectorAll(".level-button").forEach((button) => {
    button.classList.toggle("is-active", button.dataset.view === view);
  });
  document.querySelectorAll(".view").forEach((section) => {
    section.classList.toggle("is-active", section.id === `${view}-view`);
  });
  referenceNotice.style.display = view === "lessons" ? "block" : "none";
}

function setCourse(courseId) {
  currentCourse = Number(courseId);
  currentCourseLabel.textContent = `Курс ${currentCourse}`;
  renderCourseButtons();
  renderPlan();
  renderLessons();
}

document.addEventListener("click", (event) => {
  const courseButton = event.target.closest("[data-course]");
  const viewButton = event.target.closest("[data-view]");

  if (courseButton) {
    setCourse(courseButton.dataset.course);
  }

  if (viewButton) {
    setView(viewButton.dataset.view);
    window.scrollTo({ top: 0, behavior: "smooth" });
  }
});

renderMatrix();
setCourse(currentCourse);
setView(currentView);
